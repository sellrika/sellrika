/**
 * An icon's SVG markup.
 * @param name Which icon.
 * @param size Its width and height in pixels.
 * @returns The `<svg>` as a string.
 */
export function icon(name: IconName, size = 16) {
	return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${PATHS[name]}</svg>`;
}

/**
 * Put an icon in front of a button's label.
 * @param button The button.
 * @param name Which icon.
 * @returns The button.
 */
export function withIcon<T extends HTMLElement>(button: T, name: IconName) {
	button.insertAdjacentHTML("afterbegin", icon(name));
	return button;
}
