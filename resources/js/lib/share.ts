/**
 * The public address of a product page in the shop's online store.
 * @param shop The shop.
 * @param slug The product's slug.
 * @param storeUrl The store's address from the server (`store_url`): its own domain, else its subdomain.
 * @returns The absolute URL, or null while the online store is off.
 */
export function productUrl(
	shop: Pick<Shop, "online_enabled" | "slug">,
	slug: string,
	storeUrl: string | null,
): string | null {
	if (!shop.online_enabled || !shop.slug || !storeUrl) return null;
	return `${storeUrl}/p/${encodeURIComponent(slug)}`;
}

/**
 * Add the `utm_*` tags, so the shop's analytics show which network sent the visit.
 * @param url The product URL.
 * @param source The network, like "facebook".
 * @returns The URL with `utm_source` and `utm_medium=social`.
 */
export function tagged(url: string, source: string): string {
	const u = new URL(url);
	u.searchParams.set("utm_source", source);
	u.searchParams.set("utm_medium", "social");
	return u.toString();
}

/**
 * The "share" links of each network. None needs an app or an API key.
 * @param url The product URL.
 * @param text The words that go with it (the product name).
 * @returns One link per network.
 */
export function shareTargets(url: string, text: string): ShareTarget[] {
	const e = encodeURIComponent;
	/**
	 * The product URL tagged for one network, ready for a query string.
	 * @param source The network.
	 * @returns The encoded URL.
	 */
	function link(source: string) {
		return e(tagged(url, source));
	}
	return [
		{
			name: "Facebook",
			icon: ICONS.facebook.path,
			color: ICONS.facebook.color,
			url: `https://www.facebook.com/sharer/sharer.php?u=${link("facebook")}`,
		},
		{
			name: "X",
			icon: ICONS.x.path,
			color: ICONS.x.color,
			url: `https://x.com/intent/post?url=${link("x")}&text=${e(text)}`,
		},
		{
			name: "WhatsApp",
			icon: ICONS.whatsapp.path,
			color: ICONS.whatsapp.color,
			url: `https://wa.me/?text=${e(`${text} ${tagged(url, "whatsapp")}`)}`,
		},
		{
			name: "Telegram",
			icon: ICONS.telegram.path,
			color: ICONS.telegram.color,
			url: `https://t.me/share/url?url=${link("telegram")}&text=${e(text)}`,
		},
		{
			name: "LINE",
			icon: ICONS.line.path,
			color: ICONS.line.color,
			url: `https://social-plugins.line.me/lineit/share?url=${link("line")}`,
		},
		{
			name: "Viber",
			icon: ICONS.viber.path,
			color: ICONS.viber.color,
			url: `viber://forward?text=${e(`${text} ${tagged(url, "viber")}`)}`,
		},
	];
}
